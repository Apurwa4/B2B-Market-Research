import { mkdir, cp, readFile, writeFile, rm } from 'node:fs/promises';
import { build } from 'esbuild';
await rm('dist', { recursive: true, force: true });
await mkdir('dist/server', { recursive: true });
await mkdir('dist/.openai', { recursive: true });
await cp('out', 'dist/client', { recursive: true });
await build({ entryPoints: ['worker/index.mjs'], outfile: 'dist/server/index.js', bundle: true, format: 'esm', target: 'es2022', minify: true });
const hosting = JSON.parse(await readFile('.openai/hosting.json','utf8'));
await writeFile('dist/.openai/hosting.json', JSON.stringify(hosting,null,2));
console.log('Next.js static pages and persistent data API packaged in dist/.');
